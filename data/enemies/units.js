// Every opponent has one role the player can read at a glance. Besides the base numbers
// (hp, speed, damage, r, range, wind, cooldown, xp) a unit may carry:
//   attack     'melee' (default), 'projectile', 'pulse' or 'mortar'
//   burst      melee that hits all around within range + reach (shown as a ring)
//   shots      projectile pattern: count, spread (radians between shots), delay (seconds
//              between shots of a burst), radial (evenly around the unit), speed (px/s)
//   mortar     a ground mark at the player that explodes after `delay`: radius, count, scatter
//   heavy      never interrupted by hits
//   poise      after an interruption, not interrupted again for this many seconds (tanks, bugs)
//   frontDamageMultiplier  damage taken from the front
//   dash       a telegraphed lunge: trigger distance, wind, speed, time, cooldown
//   flank      approaches at this angle (radians) off the straight line, then closes in
//   keep       keeps this distance from the player (retreats when closer)
//   pack       spawns together with this many copies
//   heal       every `every` s restores `amount` of max health to allies within `radius`
//   aura       allies within `radius` take `reduction` less damage
//   deathBlast after death the body explodes: radius, delay, damage (share of its hit)
//   enrage     below `below` health: speed and attack-rate multipliers
//   slow       a landed hit slows the player by `amount` for `duration` s
//   summon     every `every` s calls `count` of `units` around itself, at most `max` alive
//   pools      every `every` s leaves `count` damaging zones near the player
//   phases     boss only: at a health share `at`, summons adds and gains new attacks
//   passive    never attacks (a structure that only summons)
//   labelAbove height of the name tag over the feet, for art taller than the radius
// Every enemy, bosses included, has this much more health and hits this much harder than
// the numbers below.
