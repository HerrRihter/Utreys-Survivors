'use strict';
const fs = require('node:fs');
const path = require('node:path');

// A deliberately limited compiler for this project's named-import modules.
// Fail on unsupported syntax instead of silently producing a broken file build.
function bundle(root, entry, output) {
  const modules = new Map();
  function visit(file) {
    if (modules.has(file)) return;
    let source = fs.readFileSync(path.join(root, file), 'utf8');
    const imports = [];
    source = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm, (_, names, relative) => {
      const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(file), relative));
      if (!relative.startsWith('.') || dependency.startsWith('../')) throw new Error(`Unsupported import in ${file}`);
      imports.push(dependency);
      return `const {${names.replace(/\s+as\s+/g, ':')}} = require(${JSON.stringify(dependency)});`;
    });
    const exports = [];
    source = source.replace(/^export\s+(const|let|function)\s+(\w+)/gm, (_, kind, name) => {
      exports.push(name);
      return `${kind} ${name}`;
    });
    source = source.replaceAll('import.meta.url', `new URL(${JSON.stringify(file)}, rootURL).href`);
    if (/^\s*(?:import|export)\b/m.test(source)) throw new Error(`Unsupported module syntax in ${file}`);
    modules.set(file, source + '\n' + exports.map(name =>
      `Object.defineProperty(exports, ${JSON.stringify(name)}, {get: () => ${name}});`).join('\n'));
    imports.forEach(visit);
  }
  visit(entry);
  const up = '../'.repeat(output.split('/').length - 1);
  return `// Generated by tools/generate-file-bundles.cjs. Edit the ES modules instead.\n` +
    `(function(){'use strict';\nconst rootURL = new URL(${JSON.stringify(up)}, document.currentScript.src);\n` +
    `const factories = {\n` + [...modules].map(([file, source]) =>
      `${JSON.stringify(file)}: function(require, exports){\n${source}\n}`).join(',\n') +
    `\n};\nconst cache = Object.create(null);\nfunction require(file){\n` +
    `if(cache[file]) return cache[file];\nconst exports = cache[file] = {};\nfactories[file](require, exports);\nreturn exports;\n}\nrequire(${JSON.stringify(entry)});\n})();\n`;
}

function generateFileBundles({root = path.resolve(__dirname, '..'), check = false} = {}) {
  const pages = ['index.html', 'opponents-preview.html', 'village-preview.html',
    ...fs.readdirSync(path.join(root, 'previews')).filter(f => f.endsWith('.html')).map(f => 'previews/' + f)];
  const outputs = [];
  for (const page of pages) {
    const html = fs.readFileSync(path.join(root, page), 'utf8');
    const match = html.match(/data-entry="([^"]+)"\s+data-file-bundle="([^"]+)"/);
    if (!match) throw new Error(`Missing launch entry: ${page}`);
    const entry = path.posix.normalize(path.posix.join(path.posix.dirname(page), match[1]));
    const output = path.posix.normalize(path.posix.join(path.posix.dirname(page), match[2]));
    const content = bundle(root, entry, output);
    const destination = path.join(root, output);
    if (check) {
      if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content)
        throw new Error(`Stale file launch bundle: ${output}. Run node tools/generate-file-bundles.cjs`);
    } else {
      fs.mkdirSync(path.dirname(destination), {recursive: true});
      fs.writeFileSync(destination, content);
    }
    outputs.push(output);
  }
  return outputs;
}
if (require.main === module) {
  console.log(`${generateFileBundles({check: process.argv.includes('--check')}).length} file launch bundles ready`);
}
module.exports = {generateFileBundles, bundle};
